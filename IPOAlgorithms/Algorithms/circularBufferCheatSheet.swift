import Foundation

//📚 Шпаргалка: Кольцевой буфер (Circular Buffer)
/**
📌 Название
Кольцевой буфер (Circular Buffer, Ring Buffer, Cyclic Array)

🎯 Суть
 Массив фиксированного размера, который логически зациклен: после последнего элемента снова идет первый.
 
 Обычный массив:   [0] → [1] → [2] → [3] → [4] → ❌ КОНЕЦ
Кольцевой массив: [0] → [1] → [2] → [3] → [4] → [0] → [1] → ... ♾️
 
🎭 Две разные концепции: Индексное кольцо vs Очередь
 В зависимости от задачи, кольцевой буфер реализуют двумя принципиально разными способами:
 
 Характеристика    🔄 1. Индексное кольцо (Навигация)      📥 2. Буфер-Очередь (FIFO)
 Суть              Массив статичен, двигается только       Данные постоянно                                   указатель index.                        пишутся/удаляются, двигаются                                                               указатели head и tail.
                   
 Главный плюс     Бесконечное переключение элементов       Экономия памяти, скорость O(1)                                                             без дорогого сдвига элементов массива.
                 
 Где применяется  Галереи, плееры (треки),                  Буферы ввода-вывода, сетевые
                  карусели баннеров.                        пакеты, потоковое аудио.
                  
 
 ⚙️ Назначение и преимущества
 ~ Экономия памяти: Не создает новые массивы при изменении данных или бесконечной навигации.
 ~ Высокая скорость: Все операции выполняются за время O(1) (мгновенно).
 ~ Циклические задачи: Идеально для алгоритмов вроде Round Robin (балансировка нагрузки).
 
 🚀 Реальные сниппеты кода
 🔄 Вариант 1: Индексное кольцо (Бесконечная навигация)
 Чтобы избежать бага с «проглатыванием» первого элемента при старте, индекс сдвигается только при запросе следующего шага:
 */
let photos = ["📸", "🏞️", "🌅", "🌉"]
var index = 0 // Начинаем со строго первого элемента

func getCurrentPhoto() -> String {
    return photos[index]
}

func nextPhoto() -> String {
    index = (index + 1) % photos.count // Формула кольца вперед
    return photos[index]
}

func previousPhoto() -> String {
    index = (index - 1 + photos.count) % photos.count // Защита от отрицательного индекса
    return photos[index]
}

/** Использование:
print(getCurrentPhoto()) // "📸" (текущий стартовый)
print(nextPhoto())        // "🏞️"
print(nextPhoto())        // "🌅"
print(previousPhoto())    // "🏞️" (вернулись назад)
 */

 // 📥 Вариант 2: Классический Ring Buffer (Потоковая очередь)
 // Реализация циклической FIFO-очередь на основе Generic типов:
 
struct CircularQueue<T> {
    private var array: [T?]
    private var head = 0
    private var tail = 0
    private var count = 0
    
    var isEmpty: Bool { count == 0 }
    var isFull: Bool { count == array.count }
    
    init(capacity: Int) {
        self.array = Array(repeating: nil, count: capacity)
    }
    
    mutating func enqueue(_ element: T) -> Bool {
        guard !isFull else { return false } // Очередь переполнена
        array[tail] = element
        tail = (tail + 1) % array.count    // Зацикливаем хвост
        count += 1
        return true
    }
    
    mutating func dequeue() -> T? {
        guard !isEmpty else { return nil }  // Очередь пуста
        let element = array[head]
        array[head] = nil                  // Освобождаем память
        head = (head + 1) % array.count    // Зацикливаем голову
        count -= 1
        return element
    }
}

/** Использование:
var queue = CircularQueue<String>(capacity: 3)
_ = queue.enqueue("A") // ✅
_ = queue.enqueue("B") // ✅
_ = queue.enqueue("C") // ✅
_ = queue.enqueue("D") // ❌ false (переполнено)

print(queue.dequeue() ?? "") // "A"
print(queue.dequeue() ?? "") // "B"

_ = queue.enqueue("D") // ✅ Встает на место "A" (индекс 0)
_ = queue.enqueue("E") // ✅ Встает на место "B" (индекс 1)
// Массив внутри выглядит так: ["D", "E", "C"]
// head указывает на 2 (на элемент "C"), tail указывает на 2 (следующая запись на индекс 2)
 */

// 🧮 Ключевые формулы и однострочники
/**
Направление          Однострочник                               Примечание
Вперед на 1 шаг      idx = (idx + 1) % count                    Обычный сдвиг.
Назад на 1 шаг       idx = (idx - 1 + count) % count            + count страхует от ухода в минус.
Вперед на N шагов    idx = (idx + step) % count                 Быстрый прыжок вперед.
Назад на N шагов     idx = (idx - step % count +
                         count) % count                         Двойной остаток нужен, если                                    step > count.
 */

// ⚠️ Edge Cases (Что проверять на собеседованиях)
/**
 ~ Массив пустой: Всегда проверяй isEmpty, иначе деление на ноль (% 0) уронит приложение.
 ~ Индекс вне диапазона: При ручном изменении проверяй index < 0 и index >= count.
 ~ Очередь полная: В Ring Buffer нужно решить: отклонять новую запись или затирать старые данные в head.
 ~ Очередь пустая: Метод dequeue() должен безопасно возвращать nil, а не падать.
 */
