struct EnumReflection {
    static func run() {
        print("▶️ Run: '🤖🔥 Enum & Self Reflection File'")
        
        /*
         ⚙️ ШПОРА ПО АРХИТЕКТУРЕ: УМНЫЙ ENUM И СЕБЯШЕЧКА (SELF)
  
         1. ЧТО ТАКОЕ ENUM В SWIFT?
         Это НЕ просто список слов. Это VALUE TYPE (тип значения), как и struct.
         Он копируется при передаче, живет изолированно и может иметь свой `init`
         и свои вычисляемые свойства (computed properties).
         
         2. КЛЮЧЕВОЕ СЛОВО `self` ("Себяшечка")
         `self` — это указатель объекта на самого себя.
         - `self = .кейс` ➡️ Объект говорит: "Моя себяшечка становится вот этим кейсом".
         - `switch self`  ➡️ Объект говорит: "Смотрю в зеркало на себяшечку, чтобы понять, кто я".
         
         3. РАЗБОР СИНТАКСИСА ИНИЦИАЛИЗАТОРА: `init(_ value: Int?)`
         - `init` ➡️ Код, который срабатывает ОДИН РАЗ в момент рождения объекта.
         - `_`    ➡️ Магия Swift. Позволяет не писать имя параметра при создании: `Reiting(777)`.
         - `value`➡️ Внутреннее имя коробки с данными, доступно только внутри `{}` инициализатора.
         - `Int?` ➡️ Опционал. Говорим: "Я готов принять на вход число или nil".
         
         4. ЗАЧЕМ НУЖЕН `self = ...` ВНУТРИ `init`?
         При рождении энам — это пустое место. У него еще нет кейса.
         Мы ОБЯЗАНЫ сказать: `self = .score(unwrappedValue)` или `self = .missing`.
         Без этого объект не родится (компилятор выдаст ошибку).
         

         🤖 АНАЛОГИЯ ИЗ ЖИЗНИ: РОБОТ-СОРТИРОВЩИК НА ЗАВОДЕ
 
         Представь робота (это наш Enum). К нему на конвейер едет коробка `value` (это `init`).
          В коробке может быть деталь (`Int`), брак (`вне диапазона`) или пустота (`nil`).
         
         Робот заглядывает внутрь коробки (код внутри `init`):
         - Видит пустоту? ➡️ Наклеивает на себя наклейку `self = .missing`.
         - Видит брак?    ➡️ Наклеивает на себя наклейку `self = .invalid`.
         - Видит деталь?  ➡️ Кладет её в свой карман и клеит наклейку `self = .score(деталь)`.
         
         А когда директор завода спрашивает: "Какой результат?", робот смотрит на свою
         наклейку (`switch self`), достает если надо деталь из кармана (`let value`)
         и выдает финальный отчет (`return result`).
         */
    }
}
